USE DB_T05429_BEATRIZ_NATHAN;

CREATE TABLE EMPLOYEE ( -- Funcionários --
	ID_EMPLOYEE INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    POSITION VARCHAR(50) NOT NULL,
    SALARY DECIMAL(10,2) NOT NULL CHECK (SALARY > 0 ), -- salário tem que ser > 0 --
    HIRE_DATE DATE NOT NULL, -- data de contratação -- 
    START_TIME TIME NOT NULL, -- hora de entrada --
	END_TIME TIME NOT NULL -- hora de saída --
);

CREATE TABLE SUPPLIER ( -- Fornecedor --
 ID_SUPPLIER INT AUTO_INCREMENT PRIMARY KEY,
 NAME VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE PRODUCT (
 ID_PRODUCT INT AUTO_INCREMENT PRIMARY KEY,
 NAME VARCHAR(100) NOT NULL UNIQUE,
 SELLING_PRICE DECIMAL(10,2) NOT NULL CHECK (SELLING_PRICE > 0), -- Preço de venda, tem que ser > 0 --
 COST_PRICE DECIMAL(10,2) NOT NULL CHECK (COST_PRICE >= 0), -- Preço de Custo --
 STOCK_QUANTITY INT NOT NULL DEFAULT 0 CHECK (STOCK_QUANTITY >= 0),
 ID_SUPPLIER INT NOT NULL,
 CONSTRAINT FK_PRODUCT_SUPPLIER FOREIGN KEY (ID_SUPPLIER) REFERENCES SUPPLIER (ID_SUPPLIER), -- chave estrangeira composta de SALE (produto + fornecedor)
 CONSTRAINT UK_PRODUCT_SUPPLIER UNIQUE (ID_PRODUCT, ID_SUPPLIER)
);

CREATE TABLE CUSTOMER (
 ID_CUSTOMER INT AUTO_INCREMENT PRIMARY KEY,
 NAME VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE SALE (
 ID_SALE INT AUTO_INCREMENT PRIMARY KEY,
 SALE_DATE DATE NOT NULL,
 QUANTITY INT NOT NULL CHECK (QUANTITY > 0),
 UNIT_PRICE DECIMAL(10,2) NOT NULL CHECK (UNIT_PRICE > 0),
 UNIT_COST DECIMAL(10,2) NOT NULL CHECK (UNIT_COST >= 0),
 PAYMENT_METHOD VARCHAR(10) NOT NULL CHECK (PAYMENT_METHOD IN ('A VISTA', 'FIADO')),
 ID_EMPLOYEE INT NOT NULL,
 ID_PRODUCT INT NOT NULL,
 ID_SUPPLIER INT NOT NULL,
 ID_CUSTOMER INT NULL,
 CONSTRAINT FK_SALE_EMPLOYEE FOREIGN KEY (ID_EMPLOYEE) REFERENCES EMPLOYEE (ID_EMPLOYEE),
 CONSTRAINT FK_SALE_SUPPLIER FOREIGN KEY (ID_SUPPLIER) REFERENCES SUPPLIER (ID_SUPPLIER), -- o fornecedor da venda precisa ser o fornecedor cadastrado para aquele produto --
 CONSTRAINT FK_SALE_PRODUCT_SUPPLIER FOREIGN KEY (ID_PRODUCT, ID_SUPPLIER) REFERENCES PRODUCT (ID_PRODUCT, ID_SUPPLIER),
 CONSTRAINT FK_SALE_CUSTOMER FOREIGN KEY (ID_CUSTOMER) REFERENCES CUSTOMER (ID_CUSTOMER), -- fiado exige cliente identificado --
 CONSTRAINT CK_SALE_CREDIT_CUSTOMER CHECK (PAYMENT_METHOD = 'A VISTA' OR ID_CUSTOMER IS NOT NULL)
);

CREATE TABLE CREDIT_PAYMENT ( -- CREDIT_PAYMENT é a tabela que registra os pagamentos de fiado, ou seja, cada vez que um cliente paga, total ou parcialmente, uma venda que levou sem pagar na hora. --
 ID_PAYMENT INT AUTO_INCREMENT PRIMARY KEY,
 ID_SALE INT NOT NULL,
 PAYMENT_DATE DATE NOT NULL,
 AMOUNT DECIMAL(10,2) NOT NULL CHECK (AMOUNT > 0),
 CONSTRAINT FK_CREDIT_PAYMENT_SALE FOREIGN KEY (ID_SALE) REFERENCES SALE (ID_SALE)
);

CREATE TABLE STOCK_MOVEMENT (
 ID_STOCK_MOVEMENT INT AUTO_INCREMENT PRIMARY KEY,
 MOVEMENT_DATE DATE NOT NULL,
 MOVEMENT_TYPE VARCHAR(10) NOT NULL CHECK (MOVEMENT_TYPE IN ('ENTRADA', 'SAÍDA')),
 QUANTITY INT NOT NULL CHECK (QUANTITY > 0),
 ID_PRODUCT INT NOT NULL,
 ID_SALE INT NULL,
 CONSTRAINT FK_STOCK_MOVEMENT_PRODUCT FOREIGN KEY (ID_PRODUCT) REFERENCES PRODUCT (ID_PRODUCT),
 CONSTRAINT FK_STOCK_MOVEMENT_SALE FOREIGN KEY (ID_SALE) REFERENCES SALE (ID_SALE)
);

CREATE TABLE FINANCIAL_MOVEMENT (
 ID_FINANCIAL_MOVEMENT INT AUTO_INCREMENT PRIMARY KEY,
 MOVEMENT_DATE DATE NOT NULL,
 MOVEMENT_TYPE VARCHAR(10) NOT NULL CHECK (MOVEMENT_TYPE IN ('RECEITA', 'DESPESA')),
 AMOUNT DECIMAL(10,2) NOT NULL CHECK (AMOUNT > 0),
 DESCRIPTION VARCHAR(150) NOT NULL,
 ID_SALE INT NULL,
 ID_PAYMENT INT NULL,
 ID_SUPPLIER INT NULL,
 ID_EMPLOYEE INT NULL,
 CONSTRAINT FK_FIN_MOVEMENT_SALE FOREIGN KEY (ID_SALE) REFERENCES SALE (ID_SALE),
 CONSTRAINT FK_FIN_MOVEMENT_PAYMENT FOREIGN KEY (ID_PAYMENT) REFERENCES CREDIT_PAYMENT (ID_PAYMENT),
 CONSTRAINT FK_FIN_MOVEMENT_SUPPLIER FOREIGN KEY (ID_SUPPLIER) REFERENCES SUPPLIER (ID_SUPPLIER),
 CONSTRAINT FK_FIN_MOVEMENT_EMPLOYEE FOREIGN KEY (ID_EMPLOYEE) REFERENCES EMPLOYEE (ID_EMPLOYEE)
);

