USE `DB_T05429_BEATRIZ_FONTES`;

CREATE TABLE BETTOR (
ID INT AUTO_INCREMENT NOT NULL UNIQUE PRIMARY KEY,
NAME VARCHAR(100) NOT NULL,
DOCUMENT VARCHAR(30) UNIQUE,
CREATED_AT DATE DEFAULT (CURDATE())
);


CREATE TABLE BET (
ID INT AUTO_INCREMENT NOT NULL UNIQUE PRIMARY KEY,
AMOUNT INT NOT NULL,
TYPE CHAR(1) CHECK(TYPE IN ('A', 'B', 'C')),
DESCRIPTION VARCHAR(20) CHECK(CHAR_LENGTH(DESCRIPTION) BETWEEN 3 AND 20),
CREATED_AT DATE DEFAULT (CURDATE()),
BETTOR_ID INT
);



