# CRIAÇÃO DA TABELA ACTOR
CREATE TABLE ACTOR (
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(128) NOT NULL,
    AGE INT,
    CHARACTER_NAME VARCHAR(128),
    SALARY FLOAT
    );
    
