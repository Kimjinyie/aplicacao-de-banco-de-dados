USE DB_T05429_BEATRIZ_FONTES;

# CRIAÇÃO DE TABELA PLAYER
CREATE TABLE PLAYER (
ID INT AUTO_INCREMENT PRIMARY KEY,
NAME VARCHAR(100),
AGE INT,
POSITION VARCHAR(50),
SALARY DECIMAL(10, 2),
TEAM_ID INT
);


# CRIAÇÃO DE TABELA TEAM
CREATE TABLE TEAM (
ID INT AUTO_INCREMENT PRIMARY KEY,
NAME VARCHAR(100),
CITY VARCHAR(100),
FOUNDATION_YEAR INT,
STADIUM VARCHAR(100)
);


# CRIAÇÃO DE TABELA MATCHES
CREATE TABLE MATCHES (
ID INT AUTO_INCREMENT PRIMARY KEY,
HOME_TEAM_ID INT,
AWAY_TEAM_ID INT,
MATCH_DATE DATE,
HOME_SCORE INT,
AWAY_SCORE INT,
STADIUM VARCHAR(100)
);


