# CRIAÇÃO DA TABELA BROADCASTER
CREATE TABLE BROADCASTER (
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(128) NOT NULL,
    COUNTRY VARCHAR(128),
    FOUNDATION_YEAR YEAR
	);

